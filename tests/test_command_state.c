#include "app_global_state.h"
#include <assert.h>
#include <math.h>
#include <stdio.h>
TickType_t test_tick;
int main(void)
{
    assert(app_get_dir_speed().direction == APP_MQTT_COMMUNICATION_CAR_DIRECTION_STOP);
    app_global_state_init();
    app_set_speed(70);
    assert(app_get_dir_speed().speed == 0);
    app_set_dir(APP_MQTT_COMMUNICATION_CAR_DIRECTION_FORWARD);
    test_tick = 499;
    assert(app_get_dir_speed().speed == 70);
    test_tick = 500;
    assert(app_get_dir_speed().speed == 0);
    app_set_dir(APP_MQTT_COMMUNICATION_CAR_DIRECTION_FORWARD);
    assert(app_get_dir_speed().speed == 0);
    app_set_speed(50);
    app_stop_motion();
    assert(app_get_dir_speed().direction == APP_MQTT_COMMUNICATION_CAR_DIRECTION_STOP);
    test_tick = UINT32_MAX - 100;
    app_set_dir(APP_MQTT_COMMUNICATION_CAR_DIRECTION_FORWARD);
    app_set_speed(30);
    test_tick = 398;
    assert(app_get_dir_speed().speed == 30);
    test_tick = 399;
    assert(app_get_dir_speed().speed == 0);
    test_tick = 1000;
    app_set_dir(APP_MQTT_COMMUNICATION_CAR_DIRECTION_FORWARD);
    app_set_speed(40);
    test_tick = 1400;
    app_set_dir(APP_MQTT_COMMUNICATION_CAR_DIRECTION_FORWARD);
    test_tick = 1500;
    assert(app_get_dir_speed().speed == 0);

    app_set_dir(APP_MQTT_COMMUNICATION_CAR_DIRECTION_FORWARD);
    app_set_speed(40);
    app_set_dir((app_car_dir_state)99);
    assert(app_get_dir_speed().speed == 0);

    app_set_dir(APP_MQTT_COMMUNICATION_CAR_DIRECTION_FORWARD);
    app_set_speed(255);
    assert(app_get_dir_speed().speed == 0);
    app_set_position(NULL);
    app_car_position position = {0};
    assert(!app_get_valid_position(&position));
    assert(!app_get_valid_position(NULL));
    test_tick = 2000;
    app_set_position(&position);
    test_tick = 2099;
    assert(app_get_valid_position(&position));
    test_tick = 2100;
    assert(!app_get_valid_position(&position));
    position.yaw = NAN;
    app_set_position(&position);
    assert(!app_get_valid_position(&position));
    position.yaw = 0;
    position.roll = INFINITY;
    app_set_position(&position);
    assert(!app_get_valid_position(&position));
    position.roll = 0;
    test_tick = UINT32_MAX - 50;
    app_set_position(&position);
    test_tick = 48;
    assert(app_get_valid_position(&position));
    test_tick = 49;
    assert(!app_get_valid_position(&position));
    app_stop_motion();
    test_tick = 3000;
    app_set_dir(APP_MQTT_COMMUNICATION_CAR_DIRECTION_FORWARD);
    assert(app_get_dir_speed().speed == 0);
    app_set_speed(60);
    assert(app_get_dir_speed().speed == 60);
    app_stop_motion();
    app_set_speed(60);
    assert(app_get_dir_speed().speed == 0);
    test_tick += APP_COMMAND_TIMEOUT_MS;
    assert(app_get_dir_speed().speed == 0);
    app_set_dir(APP_MQTT_COMMUNICATION_CAR_DIRECTION_FORWARD);
    assert(app_get_dir_speed().speed == 0);
    assert(!app_is_motion_inhibited());
    app_confirm_motor_stopped();
    assert(!app_is_motor_stop_confirmed());
    app_set_speed(60);
    assert(app_get_dir_speed().speed == 60);
    app_request_motion_inhibit();
    assert(app_is_motion_inhibited());
    assert(!app_is_motor_stop_confirmed());
    assert(app_get_dir_speed().speed == 0);
    app_set_dir(APP_MQTT_COMMUNICATION_CAR_DIRECTION_FORWARD);
    app_set_speed(60);
    assert(app_get_dir_speed().speed == 0);
    app_confirm_motor_stopped();
    assert(app_is_motor_stop_confirmed());
    app_stop_motion();
    app_request_motion_inhibit();
    assert(app_is_motion_inhibited());
    assert(app_is_motor_stop_confirmed());
    puts("command state tests passed");
}
